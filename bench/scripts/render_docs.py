def _operating_rows(
    points_by_name: Mapping[str, Mapping[str, Any]], names: Mapping[str, str]
) -> list[list[str]]:
    rows = []
    for key, label in names.items():
        op = points_by_name.get(key)
        if not op:
            continue
        row = policy_row(label, op.get("test_row", {}))
        param = (
            f"{op['param_name']} = {num(op.get('param'))}"
            if op.get("param_name")
            else "none"
        )
        rows.append([row[0], param, *row[1:]])
    return rows


