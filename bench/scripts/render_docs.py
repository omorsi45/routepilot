def render_data(run: Run) -> list[str]:
    r = run.results
    out: list[str] = []
    out += heading("Items per dataset and split")
    per = r.get("items_per_dataset_split", {})
    splits = ("train", "calib", "test", "heldout")
    rows = [
        [ds, *[v.get(s) for s in splits], sum(v.get(s, 0) for s in splits)]
        for ds, v in per.items()
    ]
    totals = r.get("split_totals", {})
    rows.append(
        [
            "total",
            *[totals.get(s) for s in splits],
            sum(totals.get(s, 0) for s in splits),
        ]
    )
    out += table(["dataset", *splits, "total"], rows)
    held = r.get("heldout_datasets", [])
    domains = r.get("heldout_domains", {})
    out.append(
        "Held-out datasets (fixed before training, used only in the shift and OOD experiments): "
        + ", ".join(f"{d} ({domains.get(d, 'n/a')})" for d in held)
        + f". Split salt `{r.get('split_salt')}`."
    )
    out.append("")
    out += heading("Pools")
    pools = r.get("pools", {})
    out += table(
        ["pool", "models", "datasets", "items", *splits, "Best Single", "cheapest"],
        [
            [
                name,
                len(p.get("models", [])),
                len(p.get("datasets", [])),
                p.get("n_items"),
                *[p.get("items_per_split", {}).get(s) for s in splits],
                p.get("best_single"),
                p.get("cheapest"),
            ]
            for name, p in pools.items()
        ],
    )
    out.append(
        "Best Single is the model with the highest success on train and calibration. "
        "Cheapest is the model with the lowest mean cost per item on train and calibration. "
        "Per-token prices are fitted from recorded costs on the train and calibration rows only."
    )
    out.append("")
    for name, p in pools.items():
        out += heading(f"Success per split, pool {name} (recorded)")
        ranked = sorted(p.get("rank", {}).items(), key=lambda kv: -kv[1])
        sbs = p.get("success_by_split", {})
        out += table(
            ["model", "rank", *splits],
            [
                [m, rank, *[fixed(sbs.get(m, {}).get(s), 3) for s in splits]]
                for m, rank in ranked
            ],
        )
        out += heading(
            f"Prices fitted from recorded costs, pool {name} (fitted, not list prices)"
        )
        low = set(p.get("low_r2_models", []))
        prices = p.get("prices", {})
        out += table(
            [
                "model",
                "input USD/Mtok",
                "output USD/Mtok",
                "fit RMSE USD",
                "R^2",
                "rows fitted",
                "note",
            ],
            [
                [
                    m,
                    fixed(v.get("in_usd_per_mtok"), 4),
                    fixed(v.get("out_usd_per_mtok"), 4),
                    fixed(v.get("fit_rmse_usd"), 6),
                    fixed(v.get("fit_r2"), 5),
                    v.get("n_fit"),
                    "R^2 below 0.9, expected costs are less accurate"
                    if m in low
                    else "",
                ]
                for m, v in prices.items()
            ],
        )
        if p.get("seven_b_models"):
            out.append(
                "Small models in this pool: "
                + ", ".join(p["seven_b_models"])
                + f". Cost basis: {p.get('seven_b_cost_basis')}."
            )
            out.append("")
    rng = r.get("r2_range", {})
    if rng:
        out.append(
            "R^2 range of the fitted prices: "
            + "; ".join(
                f"{k} {fixed(v[0], 3)} to {fixed(v[1], 3)}" for k, v in rng.items()
            )
            + "."
        )
        out.append("")
    neg = r.get("negative_token_rows")
    if neg is not None:
        out.append(
            f"Records with a negative recorded token count: {len(neg)} "
            "(listed by item and model in `results.json`). Records with zero recorded cost are "
            "kept at zero."
        )
        out.append("")
    return out


def render_baselines(run: Run) -> list[str]:
    r = run.results
    out: list[str] = [
        f"Pool {r.get('pool')}, {r.get('split')} split, {r.get('n_items')} items. "
        f"Best Single {r.get('best_single')}, cheapest {r.get('cheapest')}. "
        + bootstrap_line(r.get("bootstrap")),
        "",
    ]
    out += heading("Quality and cost on the test split, against Best Single")
    out += table(
        POLICY_HEADERS,
        [policy_row(name, row) for name, row in r.get("policies", {}).items()],
    )
    seeds = r.get("random_seeds", {})
    if seeds:
        out += heading("Random policy over seeds")
        out += table(
            ["quantity", "mean", "min", "max"],
            [
                [
                    name,
                    num(seeds[name]["mean"]),
                    num(seeds[name]["min"]),
                    num(seeds[name]["max"]),
                ]
                for name in ("success_rate", "mean_cost_usd")
                if name in seeds
            ],
        )
    mapping = r.get("rules_mapping", {})
    if mapping:
        out += heading("Static rules mapping (chosen on train and calibration)")
        out += table(
            ["rule", "model"],
            [["default", mapping.get("default_model")]]
            + [[k, v] for k, v in mapping.get("rules", {}).items()],
        )
    parity = r.get("rules_parity")
    if parity:
        out.append(
            f"Rules parity between the Python mapping and the Go router: {parity.get('items')} "
            f"items, {parity.get('mismatches')} mismatches."
        )
        out.append("")
    front = r.get("pareto_front")
    if front:
        out.append("Pareto front of the baselines: " + ", ".join(front) + ".")
        out.append("")
    return out


