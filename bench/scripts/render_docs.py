PERCENTILES = ("p50", "p90", "p95", "p99", "p99.9")


def _bucket(block: Mapping[str, Any] | None) -> str:
    """``value (lower-upper]`` of a histogram quantile; the true value lies in the bucket."""
    if not block:
        return "n/a"
    upper = block.get("upper_ms")
    return (
        f"{fixed(block.get('value_ms'), 3)} "
        f"({fixed(block.get('lower_ms'), 3)}-{'inf' if upper is None else fixed(upper, 3)}]"
    )


def _mode(stream: bool) -> str:
    return "streaming" if stream else "non-streaming"


def _client_runs(runs: Sequence[Mapping[str, Any]]) -> list[str]:
    return table(
        [
            "run",
            "scheduled",
            "completed",
            "errors",
            "dropped",
            "throughput rps",
            *PERCENTILES,
            "max",
        ],
        [
            [
                x["name"],
                x["load"].get("scheduled"),
                x["load"].get("completed"),
                x["load"].get("errors"),
                x["load"].get("dropped"),
                fixed(x["load"].get("throughput_rps"), 1),
                *[fixed(x["load"]["latency_ms"].get(p), 2) for p in PERCENTILES],
                fixed(x["load"]["latency_ms"].get("max"), 2),
            ]
            for x in runs
        ],
    )


