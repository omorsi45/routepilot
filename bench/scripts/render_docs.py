# --- selection and loading -----------------------------------------------------------------


def load_selection(results_dir: Path) -> dict[str, list[Entry]]:
    """Read and validate SELECTION.yaml (an absent file is an empty selection)."""
    path = results_dir / SELECTION_FILE
    if not path.is_file():
        return {}
    data = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
    if not isinstance(data, dict):
        raise RenderError(
            f"{SELECTION_FILE}: expected a mapping of experiment to run entries"
        )
    selection: dict[str, list[Entry]] = {}
    for experiment, raw in data.items():
        items = raw if isinstance(raw, list) else [raw]
        parsed: list[tuple[str, str | None, str]] = []
        for item in items:
            if not isinstance(item, dict) or not isinstance(item.get("run"), str):
                raise RenderError(
                    f"{SELECTION_FILE}: {experiment}: each entry needs a `run` ID"
                )
            unknown = set(item) - {"run", "status", "reason"}
            if unknown:
                raise RenderError(
                    f"{SELECTION_FILE}: {experiment}: unknown keys {sorted(unknown)}"
                )
            reason = item.get("reason")
            if (
                not isinstance(reason, str)
                or not reason.strip()
                or "\n" in reason.strip()
            ):
                raise RenderError(
                    f"{SELECTION_FILE}: {experiment}/{item['run']}: `reason` must be one line"
                )
            status = item.get("status")
            if status is not None and status not in STATUSES:
                raise RenderError(
                    f"{SELECTION_FILE}: {experiment}/{item['run']}: "
                    f"status must be one of {STATUSES}"
                )
            parsed.append((item["run"], status, reason.strip()))
        explicit_current = sum(1 for _, s, _ in parsed if s == "current")
        if explicit_current > 1:
            raise RenderError(
                f"{SELECTION_FILE}: {experiment}: more than one `current` run"
            )
        entries: list[Entry] = []
        have_current = explicit_current == 1
        for run_id, status, reason in parsed:
            if status is None:
                status = "also" if have_current else "current"
                have_current = True
            entries.append(Entry(run_id, status, reason))
        if not any(e.status == "current" for e in entries):
            raise RenderError(f"{SELECTION_FILE}: {experiment}: no run is shown")
        selection[str(experiment)] = entries
    return selection


def discover(results_dir: Path) -> dict[str, list[str]]:
    """Experiment to its run IDs (directories holding a run.json), sorted oldest first."""
    found: dict[str, list[str]] = {}
    for exp_dir in sorted(p for p in results_dir.iterdir() if p.is_dir()):
        ids = sorted(p.name for p in exp_dir.iterdir() if (p / "run.json").is_file())
        if ids:
            found[exp_dir.name] = ids
    return found


def _load_run(results_dir: Path, experiment: str, entry: Entry) -> Run:
    path = results_dir / experiment / entry.run_id
    if not (path / "run.json").is_file():
        raise RenderError(
            f"selected run {experiment}/{entry.run_id} does not exist under {results_dir}"
        )
    results_file = path / "results.json"
    if not results_file.is_file():
        if entry.status in SHOWN:
            raise RenderError(f"{experiment}/{entry.run_id} has no results.json")
        results: dict[str, Any] = {}
    else:
        results = json.loads(results_file.read_text(encoding="utf-8"))
    report_file = path / "report.md"
    return Run(
        experiment=experiment,
        run_id=entry.run_id,
        path=path,
        status=entry.status,
        reason=entry.reason,
        results=results,
        info=json.loads((path / "run.json").read_text(encoding="utf-8")),
        report=report_file.read_text(encoding="utf-8") if report_file.is_file() else "",
    )


def resolve(results_dir: Path) -> dict[str, list[Run]]:
    """The runs to show or list for every experiment: shown runs first, then older ones."""
    found = discover(results_dir)
    selection = load_selection(results_dir)
    for experiment in selection:
        if experiment not in found:
            raise RenderError(
                f"{SELECTION_FILE} names the experiment {experiment!r}, "
                f"which has no run under {results_dir}"
            )
    resolved: dict[str, list[Run]] = {}
    for experiment, ids in found.items():
        entries = selection.get(experiment)
        if entries is None:
            entries = [Entry(ids[-1], "current", "")] + [
                Entry(i, "older", "") for i in reversed(ids[:-1])
            ]
        order = {"current": 0, "also": 1, "older": 2}
        entries = sorted(entries, key=lambda e: order[e.status])
        resolved[experiment] = [_load_run(results_dir, experiment, e) for e in entries]
    return resolved


# --- assembling a document -----------------------------------------------------------------


def _gap(match: re.Match[str]) -> str:
    """What replaces a removed reference: one space when text remains on both sides, else none."""
    pre, post = match.group("pre"), match.group("post")
    following = match.string[match.end() : match.end() + 1]
    if pre and post and following and following not in ",.;:)":
        return " "
    return ""


def _sentence_start(text: str, at: int) -> bool:
    before = text[:at].rstrip(" \t")
    return not before or before[-1] in ".!?\n"


def scrub_internal_references(text: str) -> str:
    """Remove ruling and plan-task references from copied text, keeping the rest of the sentence.

    Handles ``(Ruling V9-R99)``, ``Rulings V9-R98 and V9-R99``, ``Ruling V9-R99: the rest``,
    ``per``/``see``/``in`` before a reference, ``(Task 3)`` and a bare ``Task 3``, and
    rewords the few phrases that name the design documents (``_PHRASES``).
    """
    text = _PAREN_REF.sub(_gap, text)

    def colon(match: re.Match[str]) -> str:
        nxt = match.group("next")
        return nxt.upper() if _sentence_start(match.string, match.start()) else nxt

    text = _COLON_REF.sub(colon, text)
    text = _LEAD_REF.sub(_gap, text)
    text = _BARE_REF.sub(_gap, text)
    for phrase, replacement in _PHRASES:
        text = text.replace(phrase, replacement)
    return text


def _own_labels_line(run: Run) -> str | None:
    """The run's own Labels line, character for character.

    Falls back to ``results["labels"]`` joined the way the report writer does, and then to the
    first paragraph after the run line of the report (the dataset summary has no Labels line).
    """
    for line in run.report.splitlines():
        if line.startswith(("**Labels:**", "Labels:")):
            return line
    labels = run.results.get("labels")
    if isinstance(labels, list) and labels:
        return "**Labels:** " + "; ".join(str(x) for x in labels) + "."
    paragraphs = [p.strip() for p in run.report.split("\n\n")]
    for i, para in enumerate(paragraphs[:-1]):
        if para.startswith("Run `"):
            following = paragraphs[i + 1]
            if following and not following.startswith(("#", "|", "-")):
                return "**Note from the run's report:** " + " ".join(following.split())
    return None


def labels_line(run: Run) -> str | None:
    """The run's Labels line with internal references dropped (see ``_own_labels_line``)."""
    line = _own_labels_line(run)
    return None if line is None else scrub_internal_references(line)


def limitations_of(run: Run) -> list[str]:
    """The lines of the report's ``## Limitations`` section, or an empty list."""
    lines = run.report.splitlines()
    if "## Limitations" not in lines:
        return []
    body: list[str] = []
    for line in lines[lines.index("## Limitations") + 1 :]:
        if line.startswith("## "):
            break
        body.append(line)
    while body and not body[0].strip():
        body.pop(0)
    while body and not body[-1].strip():
        body.pop()
    return [scrub_internal_references(line) for line in body]


def run_facts(run: Run) -> str:
    """Short facts that say how an older run differs (pool, protocol, phase, start time)."""
    r = run.results
    parts: list[str] = []
    pool = r.get("pool")
    if isinstance(pool, Mapping):
        pool = pool.get("pool")
    if isinstance(pool, str):
        parts.append(f"pool {pool}")
    protocol = r.get("protocol")
    if isinstance(protocol, Mapping) and protocol.get("name"):
        parts.append(f"protocol {protocol['name']}")
    if r.get("phase"):
        parts.append(f"phase {r['phase']}")
    if run.info.get("started_at"):
        parts.append(f"started {run.info['started_at']}")
    return "; ".join(parts)


def run_link(run: Run, link_prefix: str) -> str:
    return f"[`{run.run_id}`]({link_prefix}/{run.experiment}/{run.run_id}/)"


def render_run(section: Section, run: Run, link_prefix: str) -> list[str]:
    out = [f"### Run {run_link(run, link_prefix)}", ""]
    if run.reason:
        out += [f"Status: {run.status}. {run.reason}", ""]
    info = run.info
    command = " ".join(_HOME_PREFIX.sub(r"\1~/", str(c)) for c in info.get("command", []))
    facts = [f"commit {str(info['git_sha'])[:7]}" if info.get("git_sha") else None]
    if info.get("started_at"):
        facts.append(f"started {info['started_at']}")
    facts.append(_machine(info) if info.get("machine") else None)
    line = "Run facts: " + ", ".join(f for f in facts if f)
    if command:
        line += f". Command: `{command}`"
    out += [line + ".", ""]
    labels = labels_line(run)
    if labels:
        out += [labels, ""]
    out += section.render(run)
    for png in sorted(run.path.glob("*.png")):
        out += [
            f"![{png.stem}]({link_prefix}/{run.experiment}/{run.run_id}/{png.name})",
            "",
        ]
    limits = limitations_of(run)
    if limits:
        out += heading("Limitations of the measurement (copied from the run's report)")
        out += [*limits, ""]
    return out


def render_older(runs: Sequence[Run], link_prefix: str) -> list[str]:
    out = ["Older runs, listed and not shown:", ""]
    for run in runs:
        facts = run_facts(run)
        text = f"- {run_link(run, link_prefix)}"
        if run.reason:
            text += f": {run.reason}"
        if facts:
            text += f" ({facts})"
        out.append(text)
    return [*out, ""]


def build_docs(
    results_dir: Path,
    layout: Sequence[Section] | None = None,
    link_prefix: str = "../bench/results",
) -> dict[str, str]:
    """The text of every generated document, keyed by file name."""
    layout = list(LAYOUT if layout is None else layout)
    resolved = resolve(results_dir)
    known = {s.experiment for s in layout}
    for experiment in resolved:
        if experiment not in known:
            raise RenderError(
                f"the experiment {experiment!r} has runs but no section in the document layout"
            )
    docs: dict[str, str] = {}
    for doc in dict.fromkeys(s.doc for s in layout):
        title, preface = DOC_META[doc]
        sections = [s for s in layout if s.doc == doc and s.experiment in resolved]
        shown = [
            r for s in sections for r in resolved[s.experiment] if r.status in SHOWN
        ]
        lines = [GENERATED_COMMENT, "", GENERATED_NOTE, "", f"# {title}", "", *preface]
        lines += ["## Runs used in this file", ""]
        lines += table(
            ["experiment", "run", "status"],
            [[r.experiment, run_link(r, link_prefix), r.status] for r in shown],
        )
        for section in sections:
            runs = resolved[section.experiment]
            lines += [f"## {section.title}", ""]
            for run in runs:
                if run.status in SHOWN:
                    lines += render_run(section, run, link_prefix)
            older = [r for r in runs if r.status == "older"]
            if older:
                lines += render_older(older, link_prefix)
        docs[doc] = _finish(lines, doc)
    return docs


def _finish(lines: Sequence[str], doc: str) -> str:
    """Join, trim trailing blanks and spaces, refuse a dash character or an internal reference."""
    cleaned: list[str] = []
    for line in lines:
        line = line.rstrip()
        if not line and cleaned and not cleaned[-1]:
            continue
        cleaned.append(line)
    text = "\n".join(cleaned).strip("\n") + "\n"
    for char, name in ((EM_DASH, "em dash"), (EN_DASH, "en dash")):
        if char in text:
            at = text.index(char)
            context = text[max(0, at - 40) : at + 40].replace("\n", " ")
            raise RenderError(
                f"{doc} would contain an {name} (a dash character) near: {context!r}"
            )
    found = INTERNAL_REFERENCE.search(text)
    if found:
        context = text[max(0, found.start() - 40) : found.end() + 40].replace("\n", " ")
        raise RenderError(
            f"{doc} would contain an internal reference (a ruling or plan task) near: {context!r}"
        )
    return text


def write_docs(
    results_dir: Path, out_dir: Path, layout: Sequence[Section] | None = None
) -> list[Path]:
    """Write every document into ``out_dir`` with LF line endings and return the paths."""
    docs = build_docs(results_dir, layout)
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, text in docs.items():
        path = out_dir / name
        path.write_text(text, encoding="utf-8", newline="\n")
        written.append(path)
    return written


def main(argv: Sequence[str] | None = None) -> int:
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--results", type=Path, default=root / "bench" / "results")
    parser.add_argument("--out", type=Path, default=root / "docs")
    args = parser.parse_args(argv)
    try:
        written = write_docs(args.results, args.out)
    except RenderError as exc:
        print(f"render_docs: {exc}", file=sys.stderr)
        return 1
    for path in written:
        print(f"render_docs: wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
