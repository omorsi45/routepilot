"""Generate docs/results.md and docs/performance.md from the committed runs in bench/results.

Nothing in the generated files is typed by hand. Every table is read from a run's
``results.json``; the Labels line and the Limitations section are copied from the run's
``report.md``; run identity and machine come from ``run.json``.

Which run of an experiment is shown: by default the newest directory (run IDs start with a UTC
timestamp, so they sort by time). ``bench/results/SELECTION.yaml`` overrides that for the
experiments that have several runs. It maps an experiment to one entry, or to a list of entries,
each with a ``run`` ID, a one-line ``reason`` and an optional ``status``:

* ``current``: shown with its tables (at most one per experiment; the first entry by default);
* ``also``: shown with its tables next to the current run (for example the second pool);
* ``older``: listed by run ID with its reason, no tables (a superseded run).

The script fails when a selected run does not exist, when an experiment in the tree has no
section in the layout, and when the output would contain an em dash or an en dash.

Usage: python bench/scripts/render_docs.py [--results bench/results] [--out docs]
"""

