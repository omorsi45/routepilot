# --- formatting ----------------------------------------------------------------------------


def num(value: Any, digits: int = 4) -> str:
    """A number in ``digits`` significant digits; None is n/a."""
    if value is None:
        return "n/a"
    if isinstance(value, bool):
        return "yes" if value else "no"
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        text = f"{value:.{digits}g}"
        return "0" if text in ("-0", "0") else text
    return str(value)


def fixed(value: Any, places: int = 2) -> str:
    """A number with a fixed count of decimals; a negative zero prints as zero."""
    if value is None:
        return "n/a"
    text = f"{float(value):.{places}f}"
    return text[1:] if text.startswith("-") and float(text) == 0 else text


def count(value: Any) -> str:
    """A count that the run stored as a float (histogram observation counts) as a whole number."""
    return "n/a" if value is None else str(int(round(float(value))))


def pct(value: Any, places: int = 1) -> str:
    """A fraction as a percentage."""
    return "n/a" if value is None else f"{fixed(float(value) * 100, places)}%"


def points(value: Any, places: int = 2) -> str:
    """A fraction difference in percentage points, with its sign."""
    if value is None:
        return "n/a"
    text = fixed(float(value) * 100, places)
    return text if text.startswith("-") or float(text) == 0 else f"+{text}"


def pct2(value: Any) -> str:
    """A fraction as a percentage with two decimals."""
    return pct(value, 2)


def _mean_range(mean: Any, low: Any, high: Any) -> str:
    """``mean [min, max]``."""
    return f"{num(mean)} [{num(low)}, {num(high)}]"


def with_ci(value: Any, ci: Any, fmt: Callable[[Any], str] | None = None) -> str:
    """``value [low, high]`` with all three numbers formatted by ``fmt`` (default ``num``)."""
    fmt = fmt or num
    return f"{fmt(value)} {interval(ci, fmt)}"


def p50_p95(block: Mapping[str, Any] | None, places: int = 0) -> str:
    """``p50 / p95`` of a latency block."""
    block = block or {}
    return f"{fixed(block.get('p50'), places)} / {fixed(block.get('p95'), places)}"


def interval(pair: Any, fmt: Callable[[Any], str]) -> str:
    """``[low, high]`` formatted with ``fmt``; n/a when the run has no interval."""
    if not isinstance(pair, Sequence) or isinstance(pair, str) or len(pair) != 2:
        return "n/a"
    return f"[{fmt(pair[0])}, {fmt(pair[1])}]"


def cell(value: Any) -> str:
    """One table cell for any JSON value."""
    if value is None:
        return "n/a"
    if isinstance(value, Mapping):
        return ", ".join(f"{k}: {cell(v)}" for k, v in value.items())
    if isinstance(value, list | tuple):
        if len(value) == 2 and all(isinstance(v, int | float) for v in value):
            return interval(value, num)
        return ", ".join(cell(v) for v in value)
    return num(value)


def escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def table(headers: Sequence[str], rows: Sequence[Sequence[Any]]) -> list[str]:
    """A Markdown table; cells that are not strings go through ``cell``."""
    lines = ["| " + " | ".join(escape(h) for h in headers) + " |"]
    lines.append("|" + "|".join("---" for _ in headers) + "|")
    for row in rows:
        lines.append(
            "| "
            + " | ".join(escape(c if isinstance(c, str) else cell(c)) for c in row)
            + " |"
        )
    return [*lines, ""]


def rows_table(
    rows: Sequence[Mapping[str, Any]], columns: Sequence[str] | None = None
) -> list[str]:
    """A table of a list of dicts: every key of the first row, or the named columns."""
    if not rows:
        return ["No rows.", ""]
    keys = list(columns) if columns else list(rows[0].keys())
    return table(
        [k.replace("_", " ") for k in keys], [[r.get(k) for k in keys] for r in rows]
    )


def kv_table(
    values: Mapping[str, Any], header: tuple[str, str] = ("setting", "value")
) -> list[str]:
    return table(header, [[k.replace("_", " "), v] for k, v in values.items()])


def heading(title: str, level: int = 4) -> list[str]:
    return [f"{'#' * level} {title}", ""]


# --- policy rows shared by several experiments ---------------------------------------------


POLICY_HEADERS = [
    "policy",
    "n",
    "success [CI]",
    "mean cost USD [CI]",
    "success vs Best Single, points [CI]",
    "cost reduction vs Best Single [CI]",
]


def policy_row(name: str, row: Mapping[str, Any]) -> list[str]:
    """The cells of POLICY_HEADERS for a replay summary row (success and cost with intervals)."""
    return [
        name,
        num(row.get("n")),
        f"{pct(row.get('success_rate'))} {interval(row.get('success_ci'), pct)}",
        f"{num(row.get('mean_cost_usd'))} {interval(row.get('mean_cost_ci'), num)}",
        f"{points(row.get('success_delta_vs_strongest'))} "
        f"{interval(row.get('success_delta_ci'), points)}",
        f"{pct(row.get('cost_reduction_vs_strongest'))} "
        f"{interval(row.get('cost_reduction_ci'), pct)}",
    ]


def bootstrap_line(boot: Mapping[str, Any] | None) -> str:
    if not boot:
        return ""
    return (
        f"Intervals: {boot.get('method')} bootstrap over items, {boot.get('n')} resamples, "
        f"alpha {boot.get('alpha')}, seed {boot.get('seed')}."
    )


def verdict(flag: Any) -> str:
    if flag is None:
        return "n/a"
    return "met" if flag else "not met"


